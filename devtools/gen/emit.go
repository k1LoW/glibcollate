package main

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

const header = "// Code generated by devtools/gen. DO NOT EDIT.\n\n"

// tableSource writes the strcoll tables as static data, so that a table no
// imported package refers to is left out of the binary.
func tableSource(pkg, hash string, d *lcCollateData) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "// Package %s holds the strcoll tables of a compiled LC_COLLATE file\n", pkg)
	fmt.Fprintf(&b, "// whose sha256 is %s.\n", hash)
	b.WriteString("// The data was compiled by glibc's localedef from the locale sources of the\n")
	b.WriteString("// GNU C Library. See the README of this module for the notices.\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import \"github.com/k1LoW/glibctext/internal/strcoll\"\n\n")
	b.WriteString("// Table is the LC_COLLATE data strcoll reads.\n")
	b.WriteString("var Table = &strcoll.Table{\n")
	fmt.Fprintf(&b, "\tNRules: %d,\n", d.NRules)
	b.WriteString("\tRulesets: rulesets,\n")
	b.WriteString("\tTableMB: &tableMB,\n")
	b.WriteString("\tWeightMB: weightMB,\n")
	b.WriteString("\tExtraMB: extraMB,\n")
	b.WriteString("\tIndirectMB: indirectMB,\n")
	b.WriteString("}\n\n")
	writeString(&b, "rulesets", d.Rulesets)
	writeInt32s(&b, "tableMB", "[256]int32", d.TableMB[:])
	writeString(&b, "weightMB", d.WeightMB)
	writeString(&b, "extraMB", d.ExtraMB)
	writeInt32s(&b, "indirectMB", "[]int32", d.IndirectMB)
	return gofmt(&b)
}

func writeString(b *bytes.Buffer, name string, data []byte) {
	const perLine = 32
	fmt.Fprintf(b, "const %s = \"\"", name)
	for i := 0; i < len(data); i += perLine {
		b.WriteString(" +\n\t\"")
		for _, c := range data[i:min(i+perLine, len(data))] {
			fmt.Fprintf(b, "\\x%02x", c)
		}
		b.WriteString("\"")
	}
	b.WriteString("\n\n")
}

func writeInt32s(b *bytes.Buffer, name, typ string, data []int32) {
	const perLine = 8
	fmt.Fprintf(b, "var %s = %s{", name, typ)
	for i, v := range data {
		if i%perLine == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(b, "%d,", v)
	}
	b.WriteString("\n}\n\n")
}

type collationParams struct {
	Package      string
	Locale       string
	ArchiveName  string
	GlibcVersion string
	DebVersion   string
	Image        string
	Platform     string
	Hash         string
	TablePkg     string
}

var collationTmpl = template.Must(template.New("").Parse(header + `// Package {{.Package}} orders strings exactly as strcoll does for the
// {{.Locale}} locale of glibc {{.GlibcVersion}}.
//
// The tables are the compiled LC_COLLATE data of {{.ArchiveName}} in the
// locale-archive of {{.Image}}
// ({{.Platform}}), which ships Debian glibc {{.DebVersion}}.
// The sha256 of that LC_COLLATE file is {{.Hash}}.
//
// Importing this package registers [Collation] with collate.Register,
// so that collate.Lookup("{{.Locale}}", "{{.GlibcVersion}}") returns it.
package {{.Package}}

import (
	"github.com/k1LoW/glibctext/collate"
	"github.com/k1LoW/glibctext/internal/tables/{{.TablePkg}}"
)

// Collation orders strings as strcoll_l does for {{.Locale}} with glibc {{.GlibcVersion}}
// (Debian {{.DebVersion}}).
var Collation collate.Collation = {{.TablePkg}}.Table

func init() {
	collate.Register("{{.Locale}}", "{{.GlibcVersion}}", Collation)
}
`))

func collationSource(p collationParams) ([]byte, error) {
	var b bytes.Buffer
	if err := collationTmpl.Execute(&b, p); err != nil {
		return nil, err
	}
	if strings.Contains(p.Package, "-") {
		return nil, fmt.Errorf("invalid package name %s", p.Package)
	}
	return gofmt(&b)
}
